PH = re.compile(r'\{(\w+)(?:,\s*plural)?')
out = collections.OrderedDict()
out['@@locale'] = 'en'
for key, (value, types) in S.items():
    out[key] = value
    names = []
    for m in PH.finditer(value):
        n = m.group(1)
        if n not in names and n in types:
            names.append(n)
    missing = [n for n in types if n not in names]
    assert not missing, (key, missing)
    if names:
        out['@' + key] = {'placeholders': {n: {'type': types[n]} for n in names}}
with open('lib/l10n/app_en.arb', 'w', encoding='utf-8') as f:
    json.dump(out, f, ensure_ascii=False, indent=2)
    f.write('\n')
print(len(S), 'messages')
